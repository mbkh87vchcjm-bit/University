/// SQL Server 2014-compatible type descriptors used by the educational engine.
///
/// This file describes a type; it does not claim to execute SQL statements.
enum SqlTypeKind {
  bitType,
  tinyIntType,
  smallIntType,
  intType,
  bigIntType,
  decimalType,
  numericType,
  moneyType,
  smallMoneyType,
  floatType,
  realType,
  charType,
  varcharType,
  ncharType,
  nvarcharType,
  binaryType,
  varBinaryType,
  dateType,
  timeType,
  smallDateTimeType,
  dateTimeType,
  dateTime2Type,
  dateTimeOffsetType,
  uniqueIdentifierType,
  rowVersionType,
}

class SqlTypeSpec {
  final SqlTypeKind kind;
  final int? length;
  final int? precision;
  final int? scale;
  final bool isMax;

  const SqlTypeSpec._(
    this.kind, {
    this.length,
    this.precision,
    this.scale,
    this.isMax = false,
  });

  factory SqlTypeSpec.bit() => const SqlTypeSpec._(SqlTypeKind.bitType);
  factory SqlTypeSpec.tinyInt() =>
      const SqlTypeSpec._(SqlTypeKind.tinyIntType);
  factory SqlTypeSpec.smallInt() =>
      const SqlTypeSpec._(SqlTypeKind.smallIntType);
  factory SqlTypeSpec.intType() => const SqlTypeSpec._(SqlTypeKind.intType);
  factory SqlTypeSpec.bigInt() =>
      const SqlTypeSpec._(SqlTypeKind.bigIntType);

  factory SqlTypeSpec.decimal({int precision = 18, int scale = 0}) =>
      _decimal(SqlTypeKind.decimalType, precision, scale);

  factory SqlTypeSpec.numeric({int precision = 18, int scale = 0}) =>
      _decimal(SqlTypeKind.numericType, precision, scale);

  factory SqlTypeSpec.money() =>
      const SqlTypeSpec._(SqlTypeKind.moneyType);
  factory SqlTypeSpec.smallMoney() =>
      const SqlTypeSpec._(SqlTypeKind.smallMoneyType);

  factory SqlTypeSpec.float({int precision = 53}) {
    if (precision < 1 || precision > 53) {
      throw ArgumentError.value(
        precision,
        'precision',
        'FLOAT precision must be between 1 and 53.',
      );
    }
    return SqlTypeSpec._(
      SqlTypeKind.floatType,
      precision: precision,
    );
  }

  factory SqlTypeSpec.real() =>
      const SqlTypeSpec._(SqlTypeKind.realType);

  factory SqlTypeSpec.char({required int length}) =>
      _boundedLength(SqlTypeKind.charType, length, 8000);

  factory SqlTypeSpec.varchar({int? length, bool max = false}) =>
      _variableLength(SqlTypeKind.varcharType, length, max, 8000);

  factory SqlTypeSpec.nchar({required int length}) =>
      _boundedLength(SqlTypeKind.ncharType, length, 4000);

  factory SqlTypeSpec.nvarchar({int? length, bool max = false}) =>
      _variableLength(SqlTypeKind.nvarcharType, length, max, 4000);

  factory SqlTypeSpec.binary({required int length}) =>
      _boundedLength(SqlTypeKind.binaryType, length, 8000);

  factory SqlTypeSpec.varbinary({int? length, bool max = false}) =>
      _variableLength(SqlTypeKind.varBinaryType, length, max, 8000);

  factory SqlTypeSpec.date() =>
      const SqlTypeSpec._(SqlTypeKind.dateType);

  factory SqlTypeSpec.time({int scale = 7}) =>
      _scaled(SqlTypeKind.timeType, scale);

  factory SqlTypeSpec.smallDateTime() =>
      const SqlTypeSpec._(SqlTypeKind.smallDateTimeType);

  factory SqlTypeSpec.dateTime() =>
      const SqlTypeSpec._(SqlTypeKind.dateTimeType);

  factory SqlTypeSpec.dateTime2({int scale = 7}) =>
      _scaled(SqlTypeKind.dateTime2Type, scale);

  factory SqlTypeSpec.dateTimeOffset({int scale = 7}) =>
      _scaled(SqlTypeKind.dateTimeOffsetType, scale);

  factory SqlTypeSpec.uniqueIdentifier() =>
      const SqlTypeSpec._(SqlTypeKind.uniqueIdentifierType);

  /// ROWVERSION is generated by the database engine. It is not a user literal.
  factory SqlTypeSpec.rowVersion() =>
      const SqlTypeSpec._(SqlTypeKind.rowVersionType);

  static SqlTypeSpec _decimal(SqlTypeKind kind, int precision, int scale) {
    if (precision < 1 || precision > 38) {
      throw ArgumentError.value(
        precision,
        'precision',
        'DECIMAL/NUMERIC precision must be between 1 and 38.',
      );
    }
    if (scale < 0 || scale > precision) {
      throw ArgumentError.value(
        scale,
        'scale',
        'Scale must be between 0 and precision.',
      );
    }
    return SqlTypeSpec._(kind, precision: precision, scale: scale);
  }

  static SqlTypeSpec _boundedLength(
    SqlTypeKind kind,
    int length,
    int maximum,
  ) {
    if (length < 1 || length > maximum) {
      throw ArgumentError.value(
        length,
        'length',
        'Length must be between 1 and $maximum.',
      );
    }
    return SqlTypeSpec._(kind, length: length);
  }

  static SqlTypeSpec _variableLength(
    SqlTypeKind kind,
    int? length,
    bool max,
    int maximum,
  ) {
    if (max) {
      if (length != null) {
        throw ArgumentError('Specify either a length or max=true, not both.');
      }
      return SqlTypeSpec._(kind, isMax: true);
    }
    if (length == null || length < 1 || length > maximum) {
      throw ArgumentError.value(
        length,
        'length',
        'Length must be between 1 and $maximum, or max=true.',
      );
    }
    return SqlTypeSpec._(kind, length: length);
  }

  static SqlTypeSpec _scaled(SqlTypeKind kind, int scale) {
    if (scale < 0 || scale > 7) {
      throw ArgumentError.value(
        scale,
        'scale',
        'TIME/DATETIME2/DATETIMEOFFSET scale must be between 0 and 7.',
      );
    }
    return SqlTypeSpec._(kind, scale: scale);
  }

  String get displayName {
    return switch (kind) {
      SqlTypeKind.bitType => 'BIT',
      SqlTypeKind.tinyIntType => 'TINYINT',
      SqlTypeKind.smallIntType => 'SMALLINT',
      SqlTypeKind.intType => 'INT',
      SqlTypeKind.bigIntType => 'BIGINT',
      SqlTypeKind.decimalType => 'DECIMAL($precision, $scale)',
      SqlTypeKind.numericType => 'NUMERIC($precision, $scale)',
      SqlTypeKind.moneyType => 'MONEY',
      SqlTypeKind.smallMoneyType => 'SMALLMONEY',
      SqlTypeKind.floatType => 'FLOAT($precision)',
      SqlTypeKind.realType => 'REAL',
      SqlTypeKind.charType => 'CHAR($length)',
      SqlTypeKind.varcharType => isMax ? 'VARCHAR(MAX)' : 'VARCHAR($length)',
      SqlTypeKind.ncharType => 'NCHAR($length)',
      SqlTypeKind.nvarcharType =>
        isMax ? 'NVARCHAR(MAX)' : 'NVARCHAR($length)',
      SqlTypeKind.binaryType => 'BINARY($length)',
      SqlTypeKind.varBinaryType =>
        isMax ? 'VARBINARY(MAX)' : 'VARBINARY($length)',
      SqlTypeKind.dateType => 'DATE',
      SqlTypeKind.timeType => 'TIME($scale)',
      SqlTypeKind.smallDateTimeType => 'SMALLDATETIME',
      SqlTypeKind.dateTimeType => 'DATETIME',
      SqlTypeKind.dateTime2Type => 'DATETIME2($scale)',
      SqlTypeKind.dateTimeOffsetType => 'DATETIMEOFFSET($scale)',
      SqlTypeKind.uniqueIdentifierType => 'UNIQUEIDENTIFIER',
      SqlTypeKind.rowVersionType => 'ROWVERSION',
    };
  }
}
